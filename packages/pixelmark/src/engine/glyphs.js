export const LINE_GAP = 3 // blank rows between lines (text may contain line breaks)

/**
 * Make any string drawable: strip accents ("Ingénieur" → "INGENIEUR"),
 * upper-case it, and drop characters that have no glyph. Line breaks stay.
 */
export function normalizeText(text) {
  return String(text ?? '')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .split('\n')
    .map((line) => [...line].filter((ch) => GLYPHS[ch]).join('').replace(/ {2,}/g, ' ').trim())
    .filter(Boolean)
    .join('\n')
}

export const lineWidth = (line) => {
  let w = 0
  const chars = [...line]
  chars.forEach((ch, i) => {
    if (!GLYPHS[ch]) return
    w += GLYPHS[ch][0].length
    if (i < chars.length - 1) w += chars[i + 1] === '.' ? 1 : 2
  })
  return w
}

/** The canvas grid (in cells) a normalized text needs. */
export function wordmarkSize(text) {
  const lines = text.split('\n')
  const w = Math.max(1, ...lines.map(lineWidth))
  return { cols: w + PAD_X * 2, rows: lines.length * GH + (lines.length - 1) * LINE_GAP + PAD_T + PAD_B }
}
